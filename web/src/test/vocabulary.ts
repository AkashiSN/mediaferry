// §13「画面に出す言葉」の禁止語。**画面をまたぐ規則なので、1 か所にだけ持つ。**
//
// E2E（`e2e/journey.spec.ts`）が全画面の本文を巡り、`ConfirmDialog.test.tsx` が
// 確認の全種類の本文を巡る。**ダイアログは開くまで描かれない**ので、E2E の巡回
// だけでは確認の本文に届かない —— 両方が同じ一覧を見る必要がある。
//
// | 内部 | 画面 |
// | --- | --- |
// | ボリューム / デバイス | カード |
// | 転送先 / 宛先 | 送り先 |
// | ジョブ | 進行中の作業 / 作業の履歴 |
// | 結合 / マージ | つなぐ |
// | 承認待ち | 確認 |
// | プロファイル | カメラの種類 |
//
// **「破棄」は入れない。** 確認の本文が「この破棄の記録」と書いており、そこは
// 記録の説明なので正しい。禁じるのはボタンのラベルとしての「破棄する」だけで、
// それは `work/Merge.tsx` のテストが見ている。
//
// **「結合」も入れていない。** 画面の文言としては直してあり、進捗の phase `merge`
// も `components/JobProgress.tsx` が「つないでいます」に写すが、**サーバがそのまま
// 返す文字列がまだ残る**（`send` の案内に出る、送れない写真の理由。1 語ではなく、
// 生の英語ステータス付きの一群 —— `app/src/mediaferry/db/uploads.py` の
// `_choose_original` / `_choose_derived` を見よ）。範囲が Python 側に及ぶので、
// いまは網の外に置く。
//
// **「承認」も入れない。** 画面には残るが、**残ってよい場所が 1 つに絞られた**
// ——「承認する／却下する」で閉じている日時の確認（`work/Approve.tsx`）だけ。
// カードの信頼は「信頼」1 語に寄せてあり、そこへ「承認」が戻らないことは
// `work/CardDetail.test.tsx` が画面の本文を見て確かめる。**全画面の禁止語にすると、
// 日時の確認から操作の名前を奪うことになる**ので、そちらは画面ごとの網で見る。
//
// **env の key 名は入れない。** 設定 › 詳しい設定は `AUTO_IMPORT` や `DATA_ROOT` を
// **key 名のまま**並べる画面で、§13 が「env 由来の項目は錠前アイコン付きの読み取り
// 専用」と決めている —— 利用者が TrueNAS のアプリ設定で探すのはその名前そのもの。
// 一方、**説明の文に key を混ぜるのは内部の名前を出すことにあたる**ので、そちらは
// 画面ごとの試験で見る（`work/CardDetail.test.tsx`）。
